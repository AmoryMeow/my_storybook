/**
 * Writes src/palette/palette.css from src/palette/index.ts.
 * Run with `npm run palette` after changing a token.
 */
import { writeFileSync } from "node:fs";

import { COLOR_TOKENS } from "../src/palette/index.ts";

const cssValue = (value: string) => {
  const [color, alpha] = value.split("/");
  const ref = `var(--color-${color})`;
  return alpha ? `color-mix(in oklab, ${ref} ${alpha}%, transparent)` : ref;
};

const declarations = (mode: "light" | "dark", indent: string) =>
  [`${indent}color-scheme: ${mode};`, ...COLOR_TOKENS.map((token) => `${indent}--palette-${token.name}: ${cssValue(token[mode])};`)].join("\n");

const css = `/*
 * Generated by scripts/generate-palette-css.ts from src/palette/index.ts.
 * Do not edit by hand: change the token there and run \`npm run palette\`.
 *
 * Each token is a CSS variable mapped to a Tailwind color, so components write
 * \`bg-surface\` instead of pairing \`bg-white\` with \`dark:bg-slate-900\`.
 *
 * The theme follows the OS unless <html data-theme="light|dark"> overrides it
 * (the Storybook toolbar sets it). The \`dark:\` variant follows the same rule.
 */

@custom-variant dark {
  &:where([data-theme="dark"], [data-theme="dark"] *) {
    @slot;
  }
  @media (prefers-color-scheme: dark) {
    &:where(:root:not([data-theme="light"]), :root:not([data-theme="light"]) *) {
      @slot;
    }
  }
}

@theme inline {
${COLOR_TOKENS.map((token) => `  --color-${token.name}: var(--palette-${token.name});`).join("\n")}
}

:root {
${declarations("light", "  ")}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${declarations("dark", "    ")}
  }
}

:root[data-theme="dark"] {
${declarations("dark", "  ")}
}
`;

writeFileSync(new URL("../src/palette/palette.css", import.meta.url), css);
